"""RESULTS.md is generated from results/*.json only (no hand-typed numbers)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
J = lambda n: json.loads((R / n).read_text())


def pct(x):
    return "n/a" if x is None else f"{x * 100:.1f}%"


def main():
    wer, lat, pii, ret, com = J("wer.json"), J("latency.json"), J("pii.json"), J("retrieval.json"), J("commitments.json")
    ing = json.loads((R / "ingest_bulk.json").read_text().replace("'", '"'))
    ledger = [json.loads(l) for l in (R / "cost_ledger.jsonl").read_text().splitlines()]
    total = sum(r["usd"] for r in ledger)
    L = ["# Results", "", "Generated by `eval/report.py` from `results/*.json`. Data: 8 AMI meetings (CC BY 4.0), "
         f"{wer['captures']} speech captures of 30 s (~{wer['captures'] // 2} min of audio).", ""]
    L += ["## Ingestion", "", f"- {ing['events']} device events uploaded, {ing['replayed_duplicates']} of them re-sent on purpose "
          f"(flaky network); captures published to the stream: **{ing['captures_ready']}** (one per button press, no duplicates).", ""]
    b, q = lat["bulk"], lat.get("quantized")
    L += ["## Real-time transcription (local faster-whisper, CPU)", "",
          f"- Model `{lat['model']}`, int8. Per 30 s capture: p50 **{b['transcribe_ms_p50'] / 1000:.2f} s**, "
          f"p95 {b['transcribe_ms_p95'] / 1000:.2f} s, median real-time factor {b['realtime_factor_median']}.",
          f"- WER vs AMI human transcript: **{pct(wer['wer'])}** over {wer['captures']} captures ({wer['note']})."]
    if "realtime" in lat:
        rt = lat["realtime"]
        L += [f"- Real-time run ({rt['n']} captures uploaded at real speed): button release → redacted transcript stored, "
              f"p50 **{rt['e2e_ms_p50'] / 1000:.2f} s**, p95 {rt['e2e_ms_p95'] / 1000:.2f} s."]
    if q:
        L += [f"- int8 vs float32 on {q['clips']}: mean {q['int8']['mean_ms'] / 1000:.2f} s vs {q['float32']['mean_ms'] / 1000:.2f} s "
              f"(**{q['speedup_mean']}x** faster), WER {pct(q['int8']['wer'])} vs {pct(q['float32']['wer'])}."]
    L += ["", "| Meeting | WER |", "|---|---|"] + [f"| {m} | {pct(v)} |" for m, v in wer["per_meeting"].items()]
    s = pii["synthetic"]
    lk = pii["leaks"]
    L += ["", "## Privacy", "",
          f"- Synthetic test ({sum(d['n'] for d in s.values())} sentences): injected values removed "
          + ", ".join(f"{k} {d['removed']}/{d['n']}" for k, d in s.items()) + f" (overall **{pct(pii['synthetic_overall_recall'])}**).",
          f"- Real meetings: the speech recognizer heard a participant name in {lk['captures_where_asr_heard_a_name']} captures; "
          f"stored captures still containing one of the {len(lk['names_checked'])} names: **{lk['stored_captures_with_a_name_left']}**.",
          "- Raw audio is deleted from Redis right after transcription; the database holds only redacted text; "
          "only redacted text is sent to the LLM.", ""]
    L += ["## Retrieval (20 frozen questions over all 8 meetings)", "", "| Method | hit@3 | MRR@10 |", "|---|---|---|"]
    L += [f"| {k} | {v['hits']}/{v['n']} ({pct(v['hit@3'])}) | {v['mrr@10']} |" for k, v in ret.items()]
    L += ["", "## Commitment extraction vs AMI human action items", "",
          "Judge: Claude Sonnet 5.5 with a frozen prompt (`prompts/judge_v1.md`), never the model being graded. "
          "Precision is a lower bound: the human list is short and misses real commitments.", "",
          "| Setup | Source | Recall | Precision (lower bound) | Predicted | Pipeline cost |", "|---|---|---|---|---|---|"]
    names = {"rule": "Regex baseline", "haiku": "Haiku only", "routed": "Routed (Haiku → validator → Sonnet retry → Opus merge)",
             "opus": "Opus everywhere"}
    for k, v in com.items():
        mode, src = k.split("/")
        L.append(f"| {names[mode]} | {src} | {v['gold_hit']}/{v['gold']} ({pct(v['recall'])}) | "
                 f"{pct(v['precision_lower_bound'])} | {v['pred']} | ${v['pipeline_usd']:.4f} |")
    r, o = com.get("routed/whisper"), com.get("opus/whisper")
    if r and o and o["pipeline_usd"]:
        L += ["", f"Routing cost **{(1 - r['pipeline_usd'] / o['pipeline_usd']) * 100:.0f}% less** than Opus everywhere "
              f"(${r['pipeline_usd']:.4f} vs ${o['pipeline_usd']:.4f}); windows escalated to Sonnet: {r['escalated']}/{r['windows']}."]
    by = {}
    for x in ledger:
        by[x["model"]] = by.get(x["model"], 0) + x["usd"]
    L += ["", "## Cost", "", f"Total Claude spend, every run including development and judging: **${total:.4f}** "
          f"({len(ledger)} calls). Hard cap in code: `WMP_COST_CAP`.", ""]
    L += [f"- {m}: ${u:.4f}" for m, u in sorted(by.items())]
    (ROOT / "RESULTS.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
